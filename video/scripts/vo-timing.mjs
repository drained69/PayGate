// Measures each narration clip in narration/ and writes src/vo.ts: its length and the pauses
// inside it. The timeline sizes every scene from these lengths, and the subtitles snap to the
// pauses, so picture, words and voice stay together.
// Run after replacing any clip: node scripts/vo-timing.mjs
import { execFileSync, spawnSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../narration/', import.meta.url).pathname;
const out = {};
for (const file of readdirSync(dir).filter(f => f.endsWith('.m4a')).sort()) {
  const path = dir + file;
  const dur = Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path]).toString());
  const log = spawnSync('ffmpeg', ['-i', path, '-af', 'silencedetect=n=-38dB:d=0.12', '-f', 'null', '-']).stderr.toString();
  const starts = [...log.matchAll(/silence_start: ([\d.]+)/g)].map(m => Number(m[1]));
  const ends = [...log.matchAll(/silence_end: ([\d.]+)/g)].map(m => Number(m[1]));
  const gaps = starts.map((s, i) => [Number(s.toFixed(3)), Number((ends[i] ?? dur).toFixed(3))]).filter(([s, e]) => s > 0.05 && e < dur - 0.05);
  out[file.replace('.m4a', '')] = { dur: Number(dur.toFixed(3)), gaps };
}
writeFileSync(new URL('../src/vo.ts', import.meta.url),
  `// Generated by scripts/vo-timing.mjs from narration/*.m4a. Do not edit.\nexport const VO: Record<string, { dur: number; gaps: [number, number][] }> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${v.dur}s ${v.gaps.length} pauses`).join('\n'));
