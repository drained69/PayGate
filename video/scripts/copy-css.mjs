// Copies the app's real stylesheet into the video, so the rebuilt UI uses the exact tokens.
// - drops the font @import (fonts load through @remotion/google-fonts)
// - scopes everything under .pg so it cannot style the video's own captions
// - turns the phone breakpoint (max-width:760px) into rules under .pg.m, because
//   the composition is always wider than 760px and the media query would never fire
import { readFileSync, writeFileSync } from 'node:fs';

// Quoted strings (such as content:'{') are set aside first so their braces do not confuse the parser.
const strings = [];
const src = readFileSync(new URL('../../public/style.css', import.meta.url), 'utf8')
  .replace(/@import url\([^)]*\);/g, '').replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/'[^']*'|"[^"]*"/g, m => `\u0000${strings.push(m) - 1}\u0000`);

// Split into top-level blocks: plain rules and @media blocks.
const blocks = [];
for (let i = 0, depth = 0, start = 0; i < src.length; i++) {
  if (src[i] === '{') depth++;
  else if (src[i] === '}' && --depth === 0) { blocks.push(src.slice(start, i + 1).trim()); start = i + 1; }
}

const scope = (rules, prefix) => rules.replace(/([^{}]+)\{([^{}]*)\}/g, (_, sel, body) => {
  const scoped = sel.split(',').map(s => {
    s = s.trim();
    if (!s) return s;
    if (s === ':root') return prefix;
    if (s === 'body') return `${prefix} .page`;
    if (s.startsWith('dialog::backdrop')) return `${prefix} .backdrop`;
    s = s.replace(/^dialog\b/, '.dialog').replace(/#toast/g, '.toast');
    return `${prefix} ${s}`;
  }).join(',');
  return `${scoped}{${body}}`;
});

let out = '/* Generated by scripts/copy-css.mjs from public/style.css. Do not edit. */\n';
for (const b of blocks) {
  if (b.startsWith('@media(max-width:760px)')) out += scope(b.slice(b.indexOf('{') + 1, -1), '.pg.m') + '\n';
  else if (b.startsWith('@media')) continue;
  else out += scope(b, '.pg') + '\n';
}
writeFileSync(new URL('../src/app.css', import.meta.url), out.replace(/\u0000(\d+)\u0000/g, (_, i) => strings[i]));
console.log('wrote src/app.css');
